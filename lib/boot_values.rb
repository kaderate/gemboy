# frozen_string_literal: true

# GameBoy DMG-01 Boot Values
module BootValues
  DMG_IO_ROM_BOOT_VALUES = {
    0xFF01 => 0x00, # SB
    0xFF02 => 0x7E, # SC
    0xFF04 => 0xAB, # DIV
    0xFF05 => 0x00, # TIMA
    0xFF06 => 0x00, # TMA
    0xFF07 => 0xF8, # TAC
    0xFF0F => 0xE1, # IF
    0xFF10 => 0x80, # NR10
    0xFF11 => 0xBF, # NR11
    0xFF12 => 0xF3, # NR12
    0xFF13 => 0xFF, # NR13
    0xFF14 => 0xBF, # NR14
    0xFF16 => 0x3F, # NR21
    0xFF17 => 0x00, # NR22
    0xFF18 => 0xFF, # NR23
    0xFF19 => 0xBF, # NR24
    0xFF1A => 0x7F, # NR30
    0xFF1B => 0xFF, # NR31
    0xFF1C => 0x9F, # NR32
    0xFF1D => 0xFF, # NR33
    0xFF1E => 0xBF, # NR34
    0xFF20 => 0xFF, # NR41
    0xFF21 => 0x00, # NR42
    0xFF22 => 0x00, # NR43
    0xFF23 => 0xBF, # NR44
    0xFF24 => 0x77, # NR50
    0xFF25 => 0xF3, # NR51
    0xFF26 => 0xF1, # NR52
    0xFF40 => 0x91, # LCDC
    0xFF41 => 0x85, # STAT
    0xFF42 => 0x00, # SCY
    0xFF43 => 0x00, # SCX
    0xFF44 => 0x00, # LY
    0xFF45 => 0x00, # LYC
    0xFF46 => 0xFF, # DMA
    0xFF47 => 0xFC, # BGP
    0xFF48 => 0xFF, # OBP0
    0xFF49 => 0xFF, # OBP1
    0xFF4A => 0x00, # WY
    0xFF4B => 0x00 # WX
  }.freeze

  CGB_OVERRIDES_BOOT_VALUES = {
    0xFF02 => 0x7F # SC
  }.freeze

  DMG_REGISTERS_ROM_BOOT_VALUES = {
    a: 0x01,
    f: 0xB0,
    b: 0x00,
    c: 0x13,
    d: 0x00,
    e: 0xD8,
    h: 0x01,
    l: 0x4D
  }.freeze

  CGB_REGISTERS_ROM_BOOT_VALUES = {
    a: 0x11,
    f: 0xB0,
    b: 0x00,
    c: 0x00,
    d: 0xFF,
    e: 0x56,
    h: 0x00,
    l: 0x0D
  }.freeze

  def self.boot_rom_for(model_name)
    case model_name
    when :dmg then DMG_IO_ROM_BOOT_VALUES
    when :cgb then DMG_IO_ROM_BOOT_VALUES.merge(CGB_OVERRIDES_BOOT_VALUES)
    else raise "Unknown model_name: #{model_name}"
    end
  end

  def self.registers_for(model_name)
    { dmg: DMG_REGISTERS_ROM_BOOT_VALUES, cgb: CGB_REGISTERS_ROM_BOOT_VALUES }.fetch(model_name).dup
  end
end
