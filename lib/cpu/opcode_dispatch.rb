class CPU
  # Table de dispatch, indexée par opcode (256 entrées), optimisée pour le lookup.
  module OpcodeDispatch
    OPCODE_DISPATCH = Array.new(256, :op_unknown).tap do |t| # rubocop:disable Metrics/BlockLength
      t[0x00] = :op_nop
      [0x07, 0x0F, 0x17, 0x1F].each { |op| t[op] = :op_rotate_a }
      t[0xc3] = :op_jp_a16
      t[0xc2] = :op_jp_nz_a16
      t[0xca] = :op_jp_z_a16
      t[0xd2] = :op_jp_nc_a16
      t[0xda] = :op_jp_c_a16
      t[0xe9] = :op_jp_hl
      t[0xf3] = :op_di
      t[0xfb] = :op_ei
      t[0xd9] = :op_reti
      t[0xcd] = :op_call_a16
      t[0xc4] = :op_call_nz_a16
      t[0xcc] = :op_call_z_a16
      t[0xd4] = :op_call_nc_a16
      t[0xdc] = :op_call_c_a16
      t[0xC9] = :op_ret
      t[0xC0] = :op_ret_nz
      t[0xC8] = :op_ret_z
      t[0xD0] = :op_ret_nc
      t[0xD8] = :op_ret_c
      [0xC7, 0xCF, 0xD7, 0xDF, 0xE7, 0xEF, 0xF7, 0xFF].each { |op| t[op] = :op_rst }
      [0x06, 0x0E, 0x16, 0x1E, 0x26, 0x2E, 0x3E].each { |op| t[op] = :op_ld_r8_d8 }
      t[0x36] = :op_ld_hl_d8
      (0x40..0x7F).each { |op| t[op] = :op_ld_r8_r8 }
      t[0x76] = :op_halt # override: HALT prime sur le range générique LD r8,r8
      t[0x10] = :op_stop
      [0x01, 0x11, 0x21, 0x31].each { |op| t[op] = :op_ld_rr_d16 }
      t[0xF8] = :op_ld_hl_sp_r8
      t[0xF9] = :op_ld_sp_hl
      t[0x02] = :op_ld_bc_a
      t[0x12] = :op_ld_de_a
      t[0x22] = :op_ldi_hl_a
      t[0x32] = :op_ldd_hl_a
      t[0x0A] = :op_ld_a_bc
      t[0x1A] = :op_ld_a_de
      t[0x2A] = :op_ldi_a_hl
      t[0x3A] = :op_ldd_a_hl
      t[0x08] = :op_ld_a16_sp
      t[0xEA] = :op_ld_a16_a
      t[0xFA] = :op_ld_a_a16
      t[0xE0] = :op_ldh_a8_a
      t[0xF0] = :op_ldh_a_a8
      t[0xE2] = :op_ldh_c_a
      t[0xF2] = :op_ldh_a_c
      [0x05, 0x0D, 0x15, 0x1D, 0x25, 0x2D, 0x3D].each { |op| t[op] = :op_dec_r8 }
      [0x04, 0x0C, 0x14, 0x1C, 0x24, 0x2C, 0x3C].each { |op| t[op] = :op_inc_r8 }
      [0x03, 0x13, 0x23, 0x33].each { |op| t[op] = :op_inc_rr }
      [0x34, 0x35].each { |op| t[op] = :op_inc_dec_hl }
      [0xb, 0x1b, 0x2b, 0x3b].each { |op| t[op] = :op_dec_rr }
      (0x80..0x87).each { |op| t[op] = :op_add_a_r8 }
      [0x09, 0x19, 0x29, 0x39].each { |op| t[op] = :op_add_hl_rr }
      t[0xE8] = :op_add_sp_r8
      (0x90..0x97).each { |op| t[op] = :op_sub_a_r8 }
      (0x88..0x8F).each { |op| t[op] = :op_adc_a_r8 }
      t[0xC6] = :op_add_a_d8
      t[0xCE] = :op_adc_a_d8
      (0x98..0x9F).each { |op| t[op] = :op_sbc_a_r8 }
      t[0xD6] = :op_sub_a_d8
      t[0xDE] = :op_sbc_a_d8
      t[0x27] = :op_daa
      (0xA0..0xA7).each { |op| t[op] = :op_and_a_r8 }
      t[0xE6] = :op_and_a_d8
      (0xB0..0xB7).each { |op| t[op] = :op_or_a_r8 }
      t[0xF6] = :op_or_a_d8
      (0xA8..0xAF).each { |op| t[op] = :op_xor_a_r8 }
      t[0xEE] = :op_xor_a_d8
      t[0x2F] = :op_cpl
      t[0x37] = :op_scf
      t[0x3F] = :op_ccf
      (0xB8..0xBF).each { |op| t[op] = :op_cp_a }
      t[0xFE] = :op_cp_a
      [0xC5, 0xD5, 0xE5].each { |op| t[op] = :op_push_rr }
      t[0xF5] = :op_push_af
      [0xC1, 0xD1, 0xE1].each { |op| t[op] = :op_pop_rr }
      t[0xF1] = :op_pop_af
      t[0x20] = :op_jr_nz_r8
      t[0x28] = :op_jr_z_r8
      t[0x30] = :op_jr_nc_r8
      t[0x38] = :op_jr_c_r8
      t[0x18] = :op_jr_r8
      t[0xCB] = :op_prefix_cb
    end.freeze
  end
end
